const quizByLesson = new Map(
  WAREHOUSE_EQUIPMENT_VIDEO_QUIZZES.map((q) => [q.lessonId, q] as const),
)

export function quizForEquipmentLesson(lessonId: string): WarehouseVideoQuiz | undefined {
  return quizByLesson.get(lessonId)
}

/** Prior lessons must be cleared before `index` when gates are on. */
export function isEquipmentVideoUnlocked(
  index: number,
  clearedLessonIds: ReadonlySet<string>,
  lessonIdsInOrder: readonly string[],
  gatesEnabled: boolean = VIDEO_SEGMENT_GATES_ENABLED,
): boolean {
  if (!gatesEnabled) return true
  if (index <= 0) return true
  return lessonIdsInOrder.slice(0, index).every((id) => clearedLessonIds.has(id))
}

