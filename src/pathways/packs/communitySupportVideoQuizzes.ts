export function isCommunitySupportVideoUnlocked(
  index: number,
  clearedLessonIds: ReadonlySet<string>,
  lessonIdsInOrder: readonly string[],
  gatesEnabled: boolean = VIDEO_SEGMENT_GATES_ENABLED,
) {
  if (!gatesEnabled) return true
  if (index <= 0) return true
  return lessonIdsInOrder.slice(0, index).every((id) => clearedLessonIds.has(id))
}
